import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync, cpSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve, join } from "node:path";
const root = fileURLToPath(new URL("../", import.meta.url));
const run = (cmd, args, options = {}) => execFileSync(cmd, args, {cwd: root, stdio: "inherit", ...options});
const version = readFileSync(join(root, "internal/buildinfo/version.go"), "utf8").match(/var Version = "([^"\n]+)"/)[1];
const config = JSON.parse(readFileSync(join(root, "desktop/tauri.conf.json"), "utf8"));
const pkg = JSON.parse(readFileSync(join(root, "desktop/package.json"), "utf8"));
const cargo = readFileSync(join(root, "desktop/Cargo.toml"), "utf8").match(/^version = "([^"]+)"/m)[1];
if ([config.version, pkg.version, cargo].some(v => v !== version)) throw Error("Desktop, Cargo, npm and Go versions must match");
if (!["darwin", "linux"].includes(process.platform)) throw Error("Desktop v1 supports macOS/Linux only");
const triple = execFileSync("rustc", ["-vV"], {encoding: "utf8"}).match(/^host: (.+)$/m)[1];
if (!["aarch64-apple-darwin", "x86_64-apple-darwin", "aarch64-unknown-linux-gnu", "x86_64-unknown-linux-gnu"].includes(triple)) throw Error(`Unsupported host: ${triple}`);
run(process.execPath, ["scripts/web-assets.mjs", "validate"]);
const generated = resolve(root, "desktop/generated");
const binaries = resolve(root, "desktop/binaries");
mkdirSync(generated, {recursive: true}); mkdirSync(binaries, {recursive: true});
const commit = execFileSync("git", ["rev-parse", "HEAD"], {cwd: root, encoding: "utf8"}).trim();
const source_dirty = execFileSync("git", ["status", "--porcelain"], {cwd: root, encoding: "utf8"}).trim() !== "";
run("go", ["build", "-trimpath", "-ldflags", `-s -w -X github.com/szhjia/stackharbor/internal/buildinfo.Version=${version} -X github.com/szhjia/stackharbor/internal/buildinfo.Commit=${commit}`, "-o", join(binaries, `stackharbor-${triple}`), "./cmd/stackharbor"]);
cpSync(join(root, "licenses"), join(generated, "licenses"), {recursive: true});
for (const name of ["LICENSE", "THIRD_PARTY_NOTICES"]) cpSync(join(root, name), join(generated, "licenses", name));
run("python3", ["scripts/desktop-icon.py", generated]);
writeFileSync(join(generated, "build.json"), JSON.stringify({version, commit, source_dirty, target: triple, desktop_protocol: 1, frontend: JSON.parse(readFileSync(join(root, "internal/web/dist/asset-manifest.json"), "utf8"))}, null, 2) + "\n");
writeFileSync(join(generated, "target"), triple + "\n");
console.log(`Prepared desktop ${version}: ${triple}`);
